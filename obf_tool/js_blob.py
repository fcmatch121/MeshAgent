#!/usr/bin/env python3
"""Encrypt the big jsExtras JS blob in ILibDuktape_ScriptContainer.c.

Replaces `char jsExtras[] = "...";` with an include of obf_js_generated.h
(one-time heap decrypt) and rewrites the `sizeof(jsExtras) - 1` call site.
Run AFTER apply_obf.py.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from apply_obf import lex_strings, unescape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'microscript/ILibDuktape_ScriptContainer.c')
HDR = os.path.join(ROOT, 'microscript/obf_js_generated.h')

key = json_key = None
import json
key = json.load(open(os.path.join(ROOT, 'obf_tool/key.json')))['key']

text = open(SRC, encoding='utf-8', errors='ignore').read()
best = None
for (s, e, raw, wide, depth, in_init) in lex_strings(text):
    if 'jsExtras' in text[max(0, s-80):s] and not wide and len(raw) > 1000:
        best = (s, e, raw)
if not best:
    print('jsExtras literal not found'); sys.exit(1)
s, e, raw = best
units = unescape(raw, False)
print('jsExtras plaintext bytes:', len(units))

enc = []
for i, b in enumerate(units):
    enc.append((b ^ key[i % 4] ^ ((i * 31) & 0xFF)) & 0xFF)

arr = ','.join('0x%02X' % b for b in enc)
N = len(enc)
hdr = f'''#include <stdlib.h>
/* Auto-generated by obf_tool/js_blob.py - do not edit. Encrypted JS blob (jsExtras). */
static const unsigned char obf_js_data[{N}] = {{ {arr} }};
#ifndef jsExtras_len
#define jsExtras_len {N}
#endif
static char* jsExtras_buf(void)
{{
	static char *p = NULL;
	if (p == NULL)
	{{
		unsigned i;
		p = (char*)malloc({N} + 1);
		if (p != NULL)
		{{
			for (i = 0; i < {N}; ++i) {{ p[i] = (char)(obf_js_data[i] ^ obf_key(i)); }}
			p[{N}] = 0;
		}}
	}}
	return p;
}}
'''
open(HDR, 'w').write(hdr)

# replace the whole declaration (prefix included)
decl_start = text.rfind('char jsExtras[] =', 0, s)
text = text[:decl_start] + 'char *jsExtras = jsExtras_buf();' + text[e:]
# add include right after the obf_generated.h include at top
if 'obf_js_generated' not in text.split('\n', 3)[0:3].__str__():
    text = '#include "obf_generated.h"\n#include "obf_js_generated.h"\n' + text.replace('#include "obf_generated.h"\n', '', 1)
# replace sizeof usage
text = text.replace('sizeof(jsExtras) - 1', 'jsExtras_len')
open(SRC, 'w', encoding='utf-8').write(text)
print('patched:', SRC)
